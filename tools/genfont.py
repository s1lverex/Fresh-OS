#!/usr/bin/env python3
"""Turn tools/font.txt glyph art into a C array: 256 glyphs x 16 bytes."""
import sys

ROWS = 13
TOP = 1  # glyph row 0 lands on cell row 1


def main():
    src, dst = sys.argv[1], sys.argv[2]
    glyphs = {}
    cur = None
    for lineno, raw in enumerate(open(src, encoding="ascii"), 1):
        line = raw.rstrip("\n")
        if not line or line.startswith(";;"):
            continue
        if line.startswith("="):
            parts = line[1:].rsplit(" ", 1)
            name, start = parts[0], int(parts[1])
            ch = " " if name == "space" else name
            if len(ch) != 1:
                sys.exit("%s:%d: bad glyph name %r" % (src, lineno, name))
            if ord(ch) in glyphs:
                sys.exit("%s:%d: duplicate glyph %r" % (src, lineno, ch))
            cur = ord(ch)
            glyphs[cur] = (start, [])
            continue
        if cur is None or any(c not in "#." for c in line) or len(line) not in (7, 8):
            sys.exit("%s:%d: bad pixel row %r" % (src, lineno, line))
        glyphs[cur][1].append(line)
    missing = [chr(c) for c in range(32, 127) if c not in glyphs]
    if missing:
        sys.exit("font: missing glyphs: %r" % "".join(missing))

    box = [0, 0, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0, 0, 0, 0]
    table = []
    for code in range(256):
        if code in glyphs:
            start, rows = glyphs[code]
            if start + len(rows) > ROWS:
                sys.exit("font: glyph %r exceeds %d rows" % (chr(code), ROWS))
            cell = [0] * 16
            for i, r in enumerate(rows):
                v = 0
                for x, c in enumerate(r[:8]):
                    if c == "#":
                        v |= 0x80 >> x
                cell[TOP + start + i] = v
            table.append(cell)
        elif code < 32:
            table.append([0] * 16)
        else:
            table.append(box)
    with open(dst, "w") as f:
        f.write("/* generated by tools/genfont.py from tools/font.txt - do not edit */\n")
        f.write("#include <stdint.h>\nconst uint8_t font8x16[256][16] = {\n")
        for code, cell in enumerate(table):
            f.write("    {" + ", ".join("0x%02X" % b for b in cell) + "}, /* %d */\n" % code)
        f.write("};\n")


if __name__ == "__main__":
    main()
